"""`python -m app.agents.export_graph > docs/agent_graph.md`: the graph as Mermaid (stdout)."""

from pathlib import Path

from app.agents.deps import AgentDeps
from app.agents.graph import build_graph
from app.agents.tools import McpToolProvider


def main() -> None:
    deps = AgentDeps(
        tools=McpToolProvider(),
        chat_model=lambda: None,
        session_factory=lambda: None,  # type: ignore[arg-type, return-value]
        data_dir=Path("/data"),
    )
    mermaid = build_graph(deps).get_graph().draw_mermaid()
    print("# Agent graph (Module 8)\n")
    print("Generated by `python -m app.agents.export_graph`. Solid arrows are fixed edges; dashed")
    print("ones are conditional hops decided at run time (the supervisor's routing and the")
    print("hop to `error` when a node fails).\n")
    print("```mermaid")
    print(mermaid.rstrip())
    print("```")


if __name__ == "__main__":
    main()
